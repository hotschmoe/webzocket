const Path = struct {
    bytes: [path_bytes_max]u8 = undefined,
    len: u16 = 0,

    fn init(value: []const u8) !Path {
        assert(value.len > 0);
        if (value.len > path_bytes_max) return error.PathLimit;
        var result: Path = .{};
        @memcpy(result.bytes[0..value.len], value);
        result.len = @intCast(value.len);
        assert(result.len == value.len);
        return result;
    }

    fn slice(self: *const Path) []const u8 {
        assert(self.len > 0);
        assert(self.len <= path_bytes_max);
        return self.bytes[0..self.len];
    }
};

