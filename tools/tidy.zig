pub fn main(init: std.process.Init) !void {
    var output_buffer: [16384]u8 = undefined;
    var output = std.Io.File.stdout().writerStreaming(init.io, &output_buffer);
    const started = std.Io.Clock.awake.now(init.io);
    const state = try init.gpa.create(State);
    defer init.gpa.destroy(state);
    state.* = .{ .io = init.io, .output = &output.interface, .root = .cwd() };
    assert(state.paths_len == 0);
    assert(state.groups_len == 0);
    run(state, init) catch |err| {
        try state.output.print("tidy: FAIL: {t}\n", .{err});
        try print_elapsed(state, started);
        try state.output.flush();
        std.process.exit(1);
    };
    try print_elapsed(state, started);
    try state.output.flush();
}

fn print_elapsed(state: *State, started: std.Io.Timestamp) !void {
    assert(state.groups_len <= groups_max);
    const elapsed = started.durationTo(std.Io.Clock.awake.now(state.io));
    assert(elapsed.toNanoseconds() >= 0);
    try state.output.print("tidy: wall time {d} ms\n", .{elapsed.toMilliseconds()});
}

fn parse_options(init: std.process.Init) !Options {
    var result: Options = .{};
    var arguments = try init.minimal.args.iterateAllocator(init.arena.allocator());
    assert(arguments.next() != null);
    for (0..16) |_| {
        const argument = arguments.next() orelse return result;
        if (std.mem.eql(u8, argument, "--update")) {
            result.update = true;
        } else if (std.mem.eql(u8, argument, "--table")) {
            result.table = true;
        } else if (std.mem.eql(u8, argument, "--root")) {
            result.root = arguments.next() orelse return error.MissingRoot;
            if (result.root.?.len == 0) return error.MissingRoot;
        } else return error.UnknownArgument;
    }
    assert(result.update or result.table);
    return error.ArgumentLimit;
}

fn run(state: *State, init: std.process.Init) !void {
    const options = try parse_options(init);
    assert(state.paths_len == 0);
    if (options.root) |root| {
        if (options.update) return error.ReportCannotUpdate;
        state.root = try std.Io.Dir.cwd().openDir(state.io, root, .{});
        state.report_only = true;
    }
    defer if (state.report_only) state.root.close(state.io);
    if (!state.report_only) try load_held(state);
    try discover(state);
    std.mem.sort(Path, state.paths[0..state.paths_len], {}, path_less);
    for (state.paths[0..state.paths_len]) |*path| {
        const source = try read_source(state, path.slice());
        if (std.mem.endsWith(u8, path.slice(), "build.zig.zon")) {
            try check_version(state, path, source);
        } else if (is_generated(source)) {
            state.skipped[state.skipped_len] = path.*;
            state.skipped_len += 1;
        } else measure(state, path, source) catch |err| {
            try state.output.print("{s}: {t}\n", .{ path.slice(), err });
            return err;
        };
    }
    try measure_scripts(state);
    try finish_counts(state);
    assert(state.groups_len > 0);
    try print_skipped(state);
    if (options.table or state.report_only) try print_table(state);
    if (!state.report_only) try check_ratchets(state, options);
}

fn path_less(_: void, left: Path, right: Path) bool {
    assert(left.len > 0);
    assert(right.len > 0);
    return std.mem.lessThan(u8, left.slice(), right.slice());
}

fn skip_directory(name: []const u8) bool {
    assert(name.len > 0);
    assert(std.mem.indexOfScalar(u8, name, '/') == null);
    return listed(name, config.skip_directories);
}

fn in_scope(path: []const u8) bool {
    assert(path.len > 0);
    assert(path.len <= path_bytes_max);
    if (!std.mem.endsWith(u8, path, ".zig")) return false;
    for (config.roots) |pattern| if (matches_root(path, pattern)) return true;
    return false;
}

fn matches_root(path: []const u8, pattern: []const u8) bool {
    assert(path.len > 0);
    assert(pattern.len > 0);
    if (std.mem.indexOfScalar(u8, pattern, '*')) |star| {
        if (!std.mem.startsWith(u8, path, pattern[0..star])) return false;
        const slash = std.mem.indexOfScalarPos(u8, path, star, '/') orelse return false;
        return matches_tail(path[slash..], pattern[star + 1 ..]);
    }
    return matches_tail(path, pattern);
}

fn matches_tail(path: []const u8, pattern: []const u8) bool {
    assert(path.len > 0);
    assert(pattern.len > 0);
    return if (std.mem.endsWith(u8, pattern, "/"))
        std.mem.startsWith(u8, path, pattern)
    else
        std.mem.eql(u8, path, pattern);
}

fn discover(state: *State) !void {
    assert(state.directories_len == 0);
    state.directories[0] = try Path.init(".");
    state.directories_len = 1;
    var cursor: u16 = 0;
    while (cursor < state.directories_len) : (cursor += 1) {
        const parent = state.directories[cursor].slice();
        var directory = try state.root.openDir(state.io, parent, .{ .iterate = true });
        defer directory.close(state.io);
        var iterator = directory.iterate();
        for (0..entries_max) |_| {
            const entry = try iterator.next(state.io) orelse break;
            if (entry.kind == .directory and skip_directory(entry.name)) continue;
            var buffer: [path_bytes_max]u8 = undefined;
            const prefix = if (cursor == 0) "" else parent;
            const separator = if (cursor == 0) "" else "/";
            const path = try std.fmt.bufPrint(&buffer, "{s}{s}{s}", .{
                prefix, separator, entry.name,
            });
            if (entry.kind == .directory) {
                if (state.directories_len == directories_max) return error.DirectoryLimit;
                state.directories[state.directories_len] = try Path.init(path);
                state.directories_len += 1;
            } else if (entry.kind == .file and state.report_only and is_script(path)) {
                const group = try group_for(state, "repository");
                record(group, .scripts, .{ .path = try Path.init(path), .line = 1 });
            } else if (entry.kind == .file and
                (std.mem.endsWith(u8, path, ".zig") or
                    std.mem.eql(u8, entry.name, "build.zig.zon")))
            {
                if (state.paths_len == files_max) return error.FileLimit;
                state.paths[state.paths_len] = try Path.init(path);
                state.paths_len += 1;
            }
        } else return error.DirectoryEntryLimit;
    }
    assert(cursor == state.directories_len);
}

fn read_source(state: *State, path: []const u8) ![:0]const u8 {
    assert(path.len > 0);
    const bytes = try state.root.readFile(state.io, path, &state.source);
    if (bytes.len > file_bytes_max) return error.FileBytesLimit;
    state.source[bytes.len] = 0;
    assert(bytes.len <= file_bytes_max);
    return state.source[0..bytes.len :0];
}

fn is_generated(source: []const u8) bool {
    assert(source.len <= file_bytes_max);
    var lines = std.mem.splitScalar(u8, source, '\n');
    for (0..8) |_| {
        const line = lines.next() orelse break;
        for (config.generated_markers) |marker| {
            if (std.mem.indexOf(u8, line, marker) != null) return true;
        }
    }
    assert(source.len < std.math.maxInt(u32));
    return false;
}

fn group_for(state: *State, name: []const u8) !*Group {
    assert(name.len > 0);
    for (state.groups[0..state.groups_len]) |*group| {
        if (std.mem.eql(u8, group.name.slice(), name)) return group;
    }
    if (state.groups_len == groups_max) return error.GroupLimit;
    const group = &state.groups[state.groups_len];
    group.* = .{ .name = try Path.init(name) };
    state.groups_len += 1;
    assert(group.counts[0] == 0);
    return group;
}

fn source_group(state: *State, path: []const u8) !*Group {
    assert(path.len > 0);
    assert(path.len <= path_bytes_max);
    if (is_held(state, path)) return group_for(state, path);
    if (state.report_only) {
        const slash = std.mem.indexOfScalar(u8, path, '/') orelse
            return group_for(state, "*.zig");
        return group_for(state, path[0..slash]);
    }
    for (config.groups) |rule| {
        if (!std.mem.startsWith(u8, path, rule.prefix)) continue;
        const slash = std.mem.indexOfScalarPos(u8, path, rule.prefix.len, '/');
        const name = if (rule.directory and slash != null) path[0..slash.?] else rule.name;
        return group_for(state, name);
    }
    return error.UngroupedSource;
}

fn record(group: *Group, metric: Metric, site: Site) void {
    assert(site.line > 0);
    const index = @backingInt(metric);
    group.counts[index] += 1;
    const sites = &group.sites[index];
    if (sites.len < sites_max) {
        sites.items[sites.len] = site;
        sites.len += 1;
    }
    assert(sites.len <= sites_max);
}

fn listed(name: []const u8, names: []const []const u8) bool {
    assert(names.len <= files_max);
    assert(name.len <= file_bytes_max);
    for (names) |candidate| if (std.mem.eql(u8, name, candidate)) return true;
    return false;
}

fn measure(state: *State, path: *const Path, source: [:0]const u8) !void {
    assert(source.len <= file_bytes_max);
    var workspace = std.heap.FixedBufferAllocator.init(&state.parser_memory);
    const tree = Ast.parse(workspace.allocator(), source, .{}) catch
        return error.ParserMemoryLimit;
    if (tree.errors.len > 0) {
        try state.output.print("{s}: Zig parse failed\n", .{path.slice()});
        return error.InvalidZig;
    }
    if (tree.tokens.len > tokens_max) return error.TokenLimit;
    if (tree.nodes.len > nodes_max) return error.NodeLimit;
    const repository = try group_for(state, "repository");
    const tests_group = if (is_held(state, path.slice()))
        try source_group(state, path.slice())
    else
        repository;
    fill_token_lines(state, tree);
    for (0..tree.nodes.len) |index| {
        const node: Ast.Node.Index = @fromBackingInt(@intCast(index));
        if (tree.nodeTag(node) == .test_decl) record(tests_group, .tests, .{
            .path = path.*,
            .line = state.token_lines[tree.nodeMainToken(node)],
        });
    }
    if (!state.report_only and !in_scope(path.slice())) return;
    const group = try source_group(state, path.slice());
    record(group, .files, .{ .path = path.*, .line = 1 });
    measure_lines(group, path, source, tree);
    try collect_scopes(state, tree);
    try collect_functions(state, group, path, tree);
    try assign_owners(state, tree);
    mark_container_members(state, tree);
    for (0..tree.nodes.len) |index| {
        const node: Ast.Node.Index = @fromBackingInt(@intCast(index));
        measure_node(state, group, .{ .path = path.*, .line = 1 }, tree, node);
    }
    finish_functions(state, group, path);
    assert(workspace.end_index <= parser_bytes_max);
}

fn measure_lines(group: *Group, path: *const Path, source: []const u8, tree: Ast) void {
    assert(source.len <= file_bytes_max);
    var lines = std.mem.splitScalar(u8, source, '\n');
    var number: u32 = 0;
    var offset: u32 = 0;
    var token: u32 = 0;
    for (0..source.len + 1) |_| {
        const line = lines.next() orelse break;
        if (offset == source.len) break;
        number += 1;
        const end = offset + line.len;
        while (token < tree.tokens.len and tree.tokenStart(token) < offset) : (token += 1) {}
        const literal = token < tree.tokens.len and tree.tokenStart(token) < end and
            tree.tokenTag(token) == .multiline_string_literal_line;
        offset += @intCast(line.len + 1);
        const site: Site = .{ .path = path.*, .line = number };
        record(group, .lines, site);
        const text = std.mem.trimEnd(u8, line, "\r");
        const columns = std.unicode.utf8CountCodepoints(text) catch text.len;
        if (columns > 100) record(group, if (literal) .literal_long_lines else .long_lines, site);
    }
    assert(number <= source.len);
}

fn fill_token_lines(state: *State, tree: Ast) void {
    assert(tree.tokens.len <= tokens_max);
    var offset: u32 = 0;
    var line: u32 = 1;
    for (tree.tokens.items(.start), 0..) |start, index| {
        for (tree.source[offset..start]) |byte| {
            if (byte == '\n') line += 1;
        }
        state.token_lines[index] = line;
        offset = start;
    }
    assert(offset <= tree.source.len);
}

fn collect_scopes(state: *State, tree: Ast) !void {
    state.scopes_len = 0;
    assert(tree.tokens.len <= tokens_max);
    for (1..tree.nodes.len) |index| {
        const node: Ast.Node.Index = @fromBackingInt(@intCast(index));
        var buffer: [2]Ast.Node.Index = undefined;
        const container = tree.fullContainerDecl(&buffer, node) orelse continue;
        if (state.scopes_len == scopes_max) return error.ScopeLimit;
        const first = container.ast.main_token;
        const named = first >= 2 and tree.tokenTag(first - 1) == .equal;
        state.scopes[state.scopes_len] = .{
            .first = first,
            .last = tree.lastToken(node),
            .name = if (named) tree.tokenSlice(first - 2) else "",
        };
        state.scopes_len += 1;
    }
    std.mem.sort(Scope, state.scopes[0..state.scopes_len], {}, scope_less);
    var stack: [depth_max]u16 = undefined;
    var depth: u16 = 0;
    var next: u16 = 0;
    for (0..tree.tokens.len) |token| {
        for (0..depth) |_| {
            if (token <= state.scopes[stack[depth - 1]].last) break;
            depth -= 1;
        }
        if (next < state.scopes_len and state.scopes[next].first == token) {
            if (depth == depth_max) return error.SyntaxDepthLimit;
            state.scopes[next].parent = if (depth == 0) owner_none else stack[depth - 1];
            stack[depth] = next;
            depth += 1;
            next += 1;
        }
        state.token_scopes[token] = if (depth == 0) owner_none else stack[depth - 1];
    }
    assert(next == state.scopes_len);
}

fn scope_less(_: void, left: Scope, right: Scope) bool {
    assert(left.first <= left.last);
    assert(right.first <= right.last);
    return left.first < right.first;
}

fn collect_functions(state: *State, group: *Group, path: *const Path, tree: Ast) !void {
    state.functions_len = 0;
    assert(tree.nodes.len <= nodes_max);
    for (0..tree.nodes.len) |index| {
        const node: Ast.Node.Index = @fromBackingInt(@intCast(index));
        if (tree.nodeTag(node) != .fn_decl) continue;
        if (state.functions_len == functions_max) return error.FunctionLimit;
        var buffer: [1]Ast.Node.Index = undefined;
        const prototype = tree.fullFnProto(&buffer, node).?;
        const first = prototype.ast.fn_token;
        const body = tree.nodeData(node).node_and_node[1];
        const last = tree.lastToken(body);
        const line = state.token_lines[first];
        const site: Site = .{ .path = path.*, .line = line };
        const name = tree.tokenSlice(prototype.name_token.?);
        const returns_type = if (prototype.ast.return_type.unwrap()) |result|
            std.mem.eql(u8, tree.getNodeSource(result), "type")
        else
            false;
        record(group, .functions, site);
        if (returns_type) record(group, .type_functions, site) else {
            const length = state.token_lines[last] - line + 1;
            if (length > 70) record(group, .long_functions, site);
            record_longest(group, length, site);
            if (is_camel_case(name)) record(group, .camel_case, site);
        }
        var parameters = prototype.iterate(&tree);
        const receiver = if (parameters.next()) |parameter|
            if (parameter.name_token) |name_token| tree.tokenSlice(name_token) else ""
        else
            "";
        state.functions[state.functions_len] = .{
            .name = name,
            .first = first,
            .body = tree.firstToken(body),
            .last = last,
            .line = line,
            .scope = state.token_scopes[first],
            .receiver = receiver,
            .trivial = single_statement(tree, body),
        };
        state.functions_len += 1;
    }
    std.mem.sort(Function, state.functions[0..state.functions_len], {}, function_less);
    for (state.edges[0..state.functions_len]) |*row| @memset(row, 0);
    assert(state.functions_len <= functions_max);
}

fn single_statement(tree: Ast, body: Ast.Node.Index) bool {
    assert(@backingInt(body) < tree.nodes.len);
    assert(tree.tokens.len > 0);
    var buffer: [2]Ast.Node.Index = undefined;
    const statements = tree.blockStatements(&buffer, body) orelse return true;
    return statements.len == 1;
}

fn function_less(_: void, left: Function, right: Function) bool {
    assert(left.first <= left.last);
    assert(right.first <= right.last);
    return left.first < right.first;
}

fn record_longest(group: *Group, length: u32, site: Site) void {
    assert(length > 0);
    const index = @backingInt(Metric.longest_function);
    if (length > group.counts[index]) {
        group.counts[index] = length;
        group.sites[index].len = 1;
        group.sites[index].items[0] = site;
    }
    assert(group.counts[index] >= length);
}

fn is_camel_case(name: []const u8) bool {
    assert(name.len > 0);
    assert(name.len <= file_bytes_max);
    if (!std.ascii.isLower(name[0])) return false;
    for (name[1..]) |byte| if (std.ascii.isUpper(byte)) return true;
    return false;
}

fn assign_owners(state: *State, tree: Ast) !void {
    assert(tree.tokens.len <= tokens_max);
    var stack: [depth_max]u16 = undefined;
    var depth: u16 = 0;
    var next: u16 = 0;
    for (0..tree.tokens.len) |token| {
        for (0..depth) |_| {
            if (token <= state.functions[stack[depth - 1]].last) break;
            depth -= 1;
        }
        if (next < state.functions_len and state.functions[next].first == token) {
            if (depth == depth_max) return error.SyntaxDepthLimit;
            stack[depth] = next;
            depth += 1;
            next += 1;
        }
        state.token_owners[token] = if (depth == 0) owner_none else stack[depth - 1];
    }
    assert(next == state.functions_len);
}

fn mark_container_members(state: *State, tree: Ast) void {
    assert(tree.nodes.len <= nodes_max);
    @memset(state.struct_fields[0..tree.nodes.len], false);
    @memset(state.container_members[0..tree.nodes.len], false);
    for (tree.rootDecls()) |member| state.container_members[@backingInt(member)] = true;
    for (0..tree.nodes.len) |index| {
        const node: Ast.Node.Index = @fromBackingInt(@intCast(index));
        var buffer: [2]Ast.Node.Index = undefined;
        const container = tree.fullContainerDecl(&buffer, node) orelse continue;
        const is_struct = tree.tokenTag(container.ast.main_token) == .keyword_struct;
        for (container.ast.members) |member| {
            state.container_members[@backingInt(member)] = true;
            state.struct_fields[@backingInt(member)] = is_struct;
        }
    }
    assert(tree.nodes.len <= state.struct_fields.len);
}

fn measure_node(state: *State, group: *Group, base: Site, tree: Ast, node: Ast.Node.Index) void {
    assert(@backingInt(node) < tree.nodes.len);
    const token = tree.nodeMainToken(node);
    const site: Site = .{ .path = base.path, .line = state.token_lines[token] };
    if (state.struct_fields[@backingInt(node)]) measure_field(group, site, tree, node);
    if (state.container_members[@backingInt(node)] and tree.tokenTag(token) == .keyword_var) {
        record(group, .globals, site);
    }
    if (tree.fullWhile(node)) |loop| {
        if (std.mem.eql(u8, tree.getNodeSource(loop.ast.cond_expr), "true")) {
            record(group, .while_true, site);
        }
    }
    var buffer: [1]Ast.Node.Index = undefined;
    if (tree.fullCall(&buffer, node)) |call| {
        const callee = call.ast.fn_expr;
        const name = callee_name(tree, callee);
        const owner = state.token_owners[token];
        if (std.mem.eql(u8, name, "assert")) {
            record(group, .assertions, site);
            if (owner != owner_none and token >= state.functions[owner].body) {
                state.functions[owner].assertion_count += 1;
            }
        }
        measure_banned(group, site, tree, callee);
        if (owner != owner_none and token >= state.functions[owner].body) {
            if (resolve_function(state, tree, callee, owner)) |target| {
                state.edges[owner][target / 64] |= @as(u64, 1) << @intCast(target % 64);
            }
        }
    }
    assert(site.line > 0);
}

fn measure_field(group: *Group, site: Site, tree: Ast, node: Ast.Node.Index) void {
    assert(@backingInt(node) < tree.nodes.len);
    const field = tree.fullContainerField(node) orelse return;
    var type_node = field.ast.type_expr.unwrap() orelse return;
    if (tree.nodeTag(type_node) == .optional_type) type_node = tree.nodeData(type_node).node;
    if (tree.nodeTag(type_node) != .identifier) return;
    const name = tree.tokenSlice(tree.nodeMainToken(type_node));
    if (std.mem.eql(u8, name, "usize")) record(group, .usize_fields, site);
    if (name.len > 1 and (name[0] == 'u' or name[0] == 'i')) {
        _ = std.fmt.parseInt(u16, name[1..], 10) catch return;
        record(group, .sized_fields, site);
    }
    assert(name.len > 0);
}

fn callee_name(tree: Ast, node: Ast.Node.Index) []const u8 {
    assert(@backingInt(node) < tree.nodes.len);
    assert(tree.tokens.len > 0);
    return switch (tree.nodeTag(node)) {
        .identifier => tree.tokenSlice(tree.nodeMainToken(node)),
        .field_access => tree.tokenSlice(tree.nodeData(node).node_and_token[1]),
        else => "",
    };
}

fn resolve_function(state: *State, tree: Ast, callee: Ast.Node.Index, owner: u16) ?u16 {
    assert(owner < state.functions_len);
    const name = callee_name(tree, callee);
    var scope = state.functions[owner].scope;
    if (tree.nodeTag(callee) == .field_access) {
        const receiver_node = tree.nodeData(callee).node_and_token[0];
        if (tree.nodeTag(receiver_node) != .identifier) return null;
        const receiver = tree.tokenSlice(tree.nodeMainToken(receiver_node));
        if (!listed(receiver, &.{ "self", "Self", state.functions[owner].receiver })) {
            scope = named_scope(state, receiver) orelse return null;
        }
        return function_in_scope(state, name, scope);
    }
    if (tree.nodeTag(callee) != .identifier) return null;
    for (0..depth_max) |_| {
        if (function_in_scope(state, name, scope)) |found| return found;
        if (scope == owner_none) return null;
        scope = state.scopes[scope].parent;
    }
    assert(scope == owner_none);
    return null;
}

fn function_in_scope(state: *State, name: []const u8, scope: u16) ?u16 {
    assert(state.functions_len <= functions_max);
    var found: ?u16 = null;
    for (state.functions[0..state.functions_len], 0..) |function, index| {
        if (function.scope != scope) continue;
        if (!std.mem.eql(u8, name, function.name)) continue;
        if (found != null) return null;
        found = @intCast(index);
    }
    assert(found == null or found.? < state.functions_len);
    return found;
}

fn named_scope(state: *State, name: []const u8) ?u16 {
    assert(name.len > 0);
    var found: ?u16 = null;
    for (state.scopes[0..state.scopes_len], 0..) |scope, index| {
        if (!std.mem.eql(u8, name, scope.name)) continue;
        if (found != null) return null;
        found = @intCast(index);
    }
    assert(found == null or found.? < state.scopes_len);
    return found;
}

