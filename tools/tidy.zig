fn raw_namespace(tree: Ast, node: Ast.Node.Index) bool {
    assert(@backingInt(node) < tree.nodes.len);
    assert(tree.firstToken(node) <= tree.lastToken(node));
    return has_chain(tree, node, &.{ "std", "c" }) or
        has_chain(tree, node, &.{ "std", "posix" }) or
        has_chain(tree, node, &.{ "os", "linux" });
}

fn receiver_value(tree: Ast, callee: Ast.Node.Index) Ast.Node.Index {
    assert(@backingInt(callee) < tree.nodes.len);
    const first = tree.firstToken(callee);
    assert(first <= tree.lastToken(callee));
    if (tree.tokenTag(first) != .identifier) return callee;
    const receiver = tree.tokenSlice(first);
    for (tree.rootDecls()) |node| {
        const declaration = tree.fullVarDecl(node) orelse continue;
        if (tree.tokenTag(declaration.ast.mut_token) != .keyword_const) continue;
        const name = tree.tokenSlice(declaration.ast.mut_token + 1);
        if (!std.mem.eql(u8, receiver, name)) continue;
        const value = declaration.ast.init_node.unwrap() orelse return callee;
        return if (tree.nodeTag(value) == .field_access) value else callee;
    }
    return callee;
}

fn measure_banned(group: *Group, site: Site, tree: Ast, callee: Ast.Node.Index) void {
    assert(@backingInt(callee) < tree.nodes.len);
    const name = callee_name(tree, callee);
    const path_allocation = listed(name, &.{ "join", "concat" }) and
        (has_chain(tree, callee, &.{ "std", "fs" }) or
            has_chain(tree, callee, &.{ "std", "mem" }));
    if (tree.nodeTag(callee) == .field_access and
        (listed(name, &allocation_names) or listed(name, config.allocation_helpers) or
            path_allocation))
    {
        record(group, .allocation, site);
    }
    const receiver = receiver_value(tree, callee);
    const timestamp = has_chain(tree, callee, &.{ "Io", "Timestamp" }) or
        has_chain(tree, receiver, &.{ "Io", "Timestamp" });
    if (has_chain(tree, callee, &.{ "std", "time" }) or
        has_chain(tree, callee, &.{ "Io", "Clock" }) or listed(name, &clock_names) or
        (timestamp and std.mem.eql(u8, name, "now")))
    {
        record(group, .clock, site);
    }
    if (listed(name, &environment_names) or listed(name, config.environment_helpers) or
        has_chain(tree, callee, &.{ "init", "environ_map" }) or
        has_chain(tree, callee, &.{ "minimal", "environ" }))
    {
        record(group, .environment, site);
    }
    measure_system_calls(group, site, tree, callee);
    assert(site.line > 0);
}

fn measure_system_calls(group: *Group, site: Site, tree: Ast, callee: Ast.Node.Index) void {
    assert(@backingInt(callee) < tree.nodes.len);
    const name = callee_name(tree, callee);
    const receiver = receiver_value(tree, callee);
    const raw = raw_namespace(tree, callee) or raw_namespace(tree, receiver);
    if (has_chain(tree, receiver, &.{ "std", "Thread" }) or
        has_chain(tree, callee, &.{ "std", "Thread" }) or
        has_chain(tree, callee, &.{ "Io", "Threaded" }) or
        std.mem.startsWith(u8, name, "pthread_") or
        (listed(name, &thread_names) and (raw or !listed(name, &ambiguous_names))) or
        (tree.nodeTag(callee) == .field_access and listed(name, &task_names)) or
        (raw and std.mem.startsWith(u8, name, "futex"))) record(group, .threads, site);
    if ((has_chain(tree, callee, &.{ "std", "fs" }) and
        !has_chain(tree, callee, &.{ "fs", "path" })) or
        has_chain(tree, callee, &.{ "Io", "Dir" }) or
        has_chain(tree, callee, &.{ "Io", "File" }) or listed(name, &file_names) or
        listed(name, config.file_helpers) or listed(name, &stdio_names) or
        (raw and listed(name, &raw_file_names)) or
        has_chain(tree, receiver, &.{ "std", "DynLib" }) or
        has_chain(tree, callee, &.{ "std", "DynLib" }))
    {
        record(group, .files_io, site);
    }
    if (((has_chain(tree, callee, &.{ "std", "process" }) or
        has_chain(tree, receiver, &.{ "std", "process" })) and
        listed(name, &.{ "spawn", "run", "replace" })) or
        (listed(name, &process_names) and
            (!listed(name, &ambiguous_names) or raw or tree.nodeTag(callee) == .identifier)))
    {
        record(group, .processes, site);
    }
    assert(site.line > 0);
}

fn has_chain(tree: Ast, node: Ast.Node.Index, components: []const []const u8) bool {
    assert(components.len == 2);
    const first = tree.firstToken(node);
    const last = tree.lastToken(node);
    assert(first <= last);
    if (last - first < 2) return false;
    for (first..last - 1) |index| {
        const token: u32 = @intCast(index);
        if (std.mem.eql(u8, tree.tokenSlice(token), components[0]) and
            tree.tokenTag(token + 1) == .period and
            std.mem.eql(u8, tree.tokenSlice(token + 2), components[1])) return true;
    }
    return false;
}

fn finish_functions(state: *State, group: *Group, path: *const Path) void {
    assert(state.functions_len <= functions_max);
    for (state.functions[0..state.functions_len], 0..) |function, index| {
        const site: Site = .{ .path = path.*, .line = function.line };
        if (function.assertion_count == 0) record(group, .functions_no_assert, site);
        if (function.trivial) record(group, .trivial_functions, site);
        if (!function.trivial) group.assertion_credit += function.assertion_count;
        if (!function.trivial and function.assertion_count < 2) {
            record(group, .assertion_deficit, site);
        }
        if (has_edge(state, @intCast(index), @intCast(index))) {
            record(group, .self_recursion, site);
        }
        for (index + 1..state.functions_len) |other| {
            if (has_edge(state, @intCast(index), @intCast(other)) and
                has_edge(state, @intCast(other), @intCast(index)))
            {
                record(group, .mutual_recursion, site);
            }
        }
    }
    assert(group.counts[@backingInt(Metric.functions_no_assert)] <=
        group.counts[@backingInt(Metric.functions)]);
}

fn has_edge(state: *State, from: u16, to: u16) bool {
    assert(from < state.functions_len);
    assert(to < state.functions_len);
    return state.edges[from][to / 64] & (@as(u64, 1) << @intCast(to % 64)) != 0;
}

fn measure_scripts(state: *State) !void {
    assert(state.groups_len > 0);
    if (state.report_only) return;
    var child = try std.process.spawn(state.io, .{
        .argv = &.{ "git", "ls-files", "-z" },
        .stdout = .pipe,
    });
    defer child.kill(state.io);
    var reader = child.stdout.?.readerStreaming(state.io, &.{});
    const length = try reader.interface.readSliceShort(&state.source);
    child.stdout.?.close(state.io);
    child.stdout = null;
    const term = try child.wait(state.io);
    if (term != .exited or term.exited != 0) return error.GitFailed;
    if (length > file_bytes_max) return error.GitOutputLimit;
    const group = try group_for(state, "repository");
    var names = std.mem.splitScalar(u8, state.source[0..length], 0);
    for (0..files_max) |_| {
        const name = names.next() orelse break;
        if (name.len == 0) continue;
        if (is_script(name)) {
            record(group, .scripts, .{ .path = try Path.init(name), .line = 1 });
        }
    } else return error.TrackedFileLimit;
    assert(length <= file_bytes_max);
}

fn is_script(path: []const u8) bool {
    assert(path.len > 0);
    assert(path.len <= path_bytes_max);
    for (config.script_exclusions) |prefix| {
        if (std.mem.startsWith(u8, path, prefix)) return false;
    }
    return listed(std.fs.path.extension(path), &.{ ".sh", ".py", ".mjs", ".js", ".ps1" });
}

fn finish_counts(state: *State) !void {
    assert(state.groups_len > 0);
    for (state.groups[0..state.groups_len]) |*group| {
        const functions = group.counts[@backingInt(Metric.functions)] -
            group.counts[@backingInt(Metric.trivial_functions)];
        group.counts[@backingInt(Metric.assertion_deficit)] = functions * 2 -|
            group.assertion_credit;
    }
    std.sort.heap(Group, state.groups[0..state.groups_len], {}, group_less);
    assert(state.version_len > 0);
}

fn group_less(_: void, left: Group, right: Group) bool {
    assert(left.name.len > 0);
    assert(right.name.len > 0);
    return std.mem.lessThan(u8, left.name.slice(), right.name.slice());
}

fn check_version(state: *State, path: *const Path, source: [:0]const u8) !void {
    assert(source.len <= file_bytes_max);
    var workspace = std.heap.FixedBufferAllocator.init(&state.parser_memory);
    const tree = try Ast.parse(workspace.allocator(), source, .{ .mode = .zon });
    if (tree.errors.len > 0) return error.InvalidManifest;
    var found = false;
    for (0..tree.tokens.len) |index| {
        const token: u32 = @intCast(index);
        if (!std.mem.eql(u8, tree.tokenSlice(token), "minimum_zig_version")) continue;
        if (index + 2 >= tree.tokens.len) return error.InvalidManifest;
        if (tree.tokenTag(token + 2) != .string_literal) return error.InvalidManifest;
        var buffer: [128]u8 = undefined;
        var writer = std.Io.Writer.fixed(&buffer);
        const literal = tree.tokenSlice(token + 2);
        const parsing = std.zig.string_literal.parseWrite(&writer, literal);
        const decoded = parsing catch return error.VersionBytesLimit;
        if (decoded != .success) return error.InvalidManifest;
        const value = writer.buffered();
        if (value.len == 0) return error.InvalidManifest;
        found = true;
        if (state.version_len == 0) {
            @memcpy(state.version[0..value.len], value);
            state.version_len = @intCast(value.len);
            state.version_path = path.*;
        } else if (!std.mem.eql(u8, value, state.version[0..state.version_len])) {
            try state.output.print("version disagreement: {s} {s}, {s} {s}\n", .{
                state.version_path.slice(), state.version[0..state.version_len],
                path.slice(),               value,
            });
            return error.VersionDisagreement;
        }
    }
    if (!found) {
        try state.output.print("{s}: missing minimum_zig_version\n", .{path.slice()});
        return error.MissingZigVersion;
    }
    assert(state.version_len > 0);
}

fn print_skipped(state: *State) !void {
    assert(state.skipped_len <= files_max);
    try state.output.print("tidy: Zig minimum {s}; skipped generated files ({d}):\n", .{
        state.version[0..state.version_len], state.skipped_len,
    });
    for (state.skipped[0..state.skipped_len]) |*path| {
        try state.output.print("  {s}\n", .{path.slice()});
    }
    assert(state.version_len > 0);
}

fn print_table(state: *State) !void {
    assert(state.groups_len > 0);
    try state.output.writeAll("| group |");
    for (std.enums.values(Metric)) |metric| {
        try state.output.print(" {s} |", .{@tagName(metric)});
    }
    try state.output.writeAll("\n|---|");
    for (0..metrics_count) |_| try state.output.writeAll("---:|");
    try state.output.writeByte('\n');
    var totals: Counts = @splat(0);
    var source_totals: Counts = @splat(0);
    for (state.groups[0..state.groups_len]) |*group| {
        try print_row(state.output, group.name.slice(), group.counts);
        add_counts(&totals, group.counts);
        if (std.mem.eql(u8, group.name.slice(), "src") or
            std.mem.startsWith(u8, group.name.slice(), "src/"))
        {
            add_counts(&source_totals, group.counts);
        }
    }
    try print_row(state.output, "**src total**", source_totals);
    try print_row(state.output, "**total**", totals);
    assert(totals[@backingInt(Metric.files)] > 0);
}

fn add_counts(totals: *Counts, counts: Counts) void {
    assert(counts[@backingInt(Metric.longest_function)] <= file_bytes_max);
    for (std.enums.values(Metric)) |metric| {
        const index = @backingInt(metric);
        if (metric == .longest_function) {
            totals[index] = @max(totals[index], counts[index]);
        } else totals[index] += counts[index];
    }
    assert(totals[@backingInt(Metric.files)] <= files_max);
}

fn print_row(output: *std.Io.Writer, name: []const u8, counts: Counts) !void {
    assert(name.len > 0);
    try output.print("| {s} |", .{name});
    for (counts) |value| try output.print(" {d} |", .{value});
    try output.writeByte('\n');
    assert(counts[@backingInt(Metric.files)] <= files_max);
}

fn at_target(counts: Counts) bool {
    assert(counts[@backingInt(Metric.functions)] <= files_max * functions_max);
    assert(counts[@backingInt(Metric.files)] <= files_max);
    for ([_]Metric{
        .long_lines,     .long_functions,   .assertion_deficit, .usize_fields,
        .self_recursion, .mutual_recursion, .while_true,        .camel_case,
        .tests,
    }) |metric| if (counts[@backingInt(metric)] != 0) return false;
    return counts[@backingInt(Metric.longest_function)] <= 70;
}

fn require_target(state: *State, group: *const Group) !bool {
    assert(group.name.len > 0);
    assert(group.counts[@backingInt(Metric.files)] <= files_max);
    if (at_target(group.counts)) return true;
    try state.output.print("{s}: new code must meet docs/TIGERSTYLE.md\n", .{
        group.name.slice(),
    });
    for ([_]Metric{
        .long_lines,     .long_functions,   .assertion_deficit, .usize_fields,
        .self_recursion, .mutual_recursion, .while_true,        .camel_case,
        .tests,
    }) |metric| {
        const value = group.counts[@backingInt(metric)];
        if (value != 0) try print_movement(state, group, metric, 0, value);
    }
    const longest = group.counts[@backingInt(Metric.longest_function)];
    if (longest > 70) try print_movement(state, group, .longest_function, 70, longest);
    return false;
}

fn read_snapshot(state: *State) !Snapshot {
    assert(!state.report_only);
    const bytes = try read_source(state, ratchet_path);
    var workspace = std.heap.FixedBufferAllocator.init(&state.parser_memory);
    const allocator = workspace.allocator();
    var diagnostics: std.zon.parse.Diagnostics = undefined;
    const snapshot = std.zon.parse.fromSlice(Snapshot, .{
        .gpa = allocator,
        .arena = allocator,
        .source = bytes,
        .diagnostics = &diagnostics,
    }) catch |err| {
        if (err == error.OutOfMemory) return error.RatchetMemoryLimit;
        try state.output.print("{f}\n", .{diagnostics.fmt(ratchet_path)});
        return err;
    };
    if (snapshot.groups.len > groups_max) return error.RatchetGroupLimit;
    for (ratcheted, snapshot.metrics) |metric, name| {
        if (!std.mem.eql(u8, @tagName(metric), name)) return error.RatchetMetricOrder;
    }
    assert(snapshot.groups.len <= groups_max);
    return snapshot;
}

fn load_held(state: *State) !void {
    assert(state.held_len == 0);
    const snapshot = try read_snapshot(state);
    if (snapshot.held_files.len > files_max) return error.HeldFileLimit;
    for (snapshot.held_files) |path| {
        if (!in_scope(path) or std.fs.path.isAbsolute(path)) return error.InvalidHeldFile;
        var components = std.mem.splitScalar(u8, path, '/');
        while (components.next()) |component| {
            if (listed(component, &.{ "", ".", ".." }) or skip_directory(component)) {
                return error.InvalidHeldFile;
            }
        }
        if (is_held(state, path)) return error.DuplicateHeldFile;
        state.held[state.held_len] = try Path.init(path);
        state.held_len += 1;
    }
    assert(state.held_len == snapshot.held_files.len);
}

fn is_held(state: *const State, path: []const u8) bool {
    assert(state.held_len <= files_max);
    assert(path.len > 0);
    for (state.held[0..state.held_len]) |*held| {
        if (std.mem.eql(u8, path, held.slice())) return true;
    }
    return false;
}

fn check_held(state: *State) !bool {
    assert(state.held_len <= files_max);
    var valid = true;
    for (state.held[0..state.held_len]) |*held| {
        const group = try group_for(state, held.slice());
        if (group.counts[@backingInt(Metric.files)] != 1) {
            try state.output.print("{s}: held file missing or excluded\n", .{held.slice()});
            valid = false;
        }
        if (!try require_target(state, group)) valid = false;
    }
    assert(state.groups_len > 0);
    return valid;
}

fn check_ratchets(state: *State, options: Options) !void {
    const snapshot = try read_snapshot(state);
    assert(!state.report_only);
    var failed = false;
    if (!try check_held(state)) failed = true;
    for (state.groups[0..state.groups_len]) |*group| {
        const old = try find_row(snapshot, group.name.slice());
        if (old) |row| {
            for (ratcheted, row.counts) |metric, before| {
                const after = group.counts[@backingInt(metric)];
                if (before == after) continue;
                try print_movement(state, group, metric, before, after);
                if (!options.update or after > before) failed = true;
            }
        } else {
            try state.output.print("{s}: new group; --update requires docs/TIGERSTYLE.md\n", .{
                group.name.slice(),
            });
            const target = try require_target(state, group);
            if (!options.update or !target) failed = true;
        }
    }
    failed = try check_removed(state, snapshot, options) or failed;
    if (failed) return error.RatchetMoved;
    if (options.update) try write_ratchets(state);
    assert(!failed);
    try state.output.writeAll("tidy: PASS\n");
}

fn find_row(snapshot: Snapshot, name: []const u8) !?Row {
    assert(name.len > 0);
    var found: ?Row = null;
    for (snapshot.groups) |row| {
        if (!std.mem.eql(u8, row.name, name)) continue;
        if (found != null) return error.DuplicateRatchetGroup;
        found = row;
    }
    assert(found == null or std.mem.eql(u8, found.?.name, name));
    return found;
}

fn print_movement(state: *State, group: *const Group, metric: Metric, old: u64, new: u64) !void {
    assert(old != new);
    try state.output.print("{s}: {s} moved: {d} -> {d}\n", .{
        group.name.slice(), @tagName(metric), old, new,
    });
    const sites = &group.sites[@backingInt(metric)];
    for (sites.items[0..sites.len]) |*site| {
        try state.output.print("  {s}:{d}\n", .{ site.path.slice(), site.line });
    }
    if (sites.len == 0) try state.output.writeAll("  (no remaining sites)\n");
    assert(sites.len <= sites_max);
}

fn check_removed(state: *State, snapshot: Snapshot, options: Options) !bool {
    assert(snapshot.groups.len <= groups_max);
    var failed = false;
    for (snapshot.groups) |row| {
        var found = false;
        for (state.groups[0..state.groups_len]) |*group| {
            if (std.mem.eql(u8, row.name, group.name.slice())) found = true;
        }
        if (found) continue;
        var empty: Group = .{ .name = try Path.init(row.name) };
        for (ratcheted, row.counts) |metric, old| {
            if (old != 0) try print_movement(state, &empty, metric, old, 0);
        }
        if (!options.update) failed = true;
    }
    assert(state.groups_len > 0);
    return failed;
}

fn write_ratchets(state: *State) !void {
    assert(state.groups_len > 0);
    var writer = std.Io.Writer.fixed(&state.report);
    try writer.writeAll(".{\n    .held_files = .{\n");
    for (state.held[0..state.held_len]) |*held| {
        try writer.print("        \"{f}\",\n", .{std.zig.fmtString(held.slice())});
    }
    try writer.writeAll("    },\n    .metrics = .{\n");
    for (ratcheted) |metric| {
        try writer.print("        \"{s}\",\n", .{@tagName(metric)});
    }
    try writer.writeAll("    },\n    .groups = .{\n");
    for (state.groups[0..state.groups_len]) |*group| {
        try writer.print("        .{{\n            .name = \"{f}\",\n", .{
            std.zig.fmtString(group.name.slice()),
        });
        try writer.writeAll("            .counts = .{\n");
        var widths: [6]u8 = @splat(0);
        var buffer: [20]u8 = undefined;
        for (ratcheted, 0..) |metric, index| {
            const value = group.counts[@backingInt(metric)];
            const number = try std.fmt.bufPrint(&buffer, "{d}", .{value});
            widths[index % 6] = @max(widths[index % 6], @as(u8, @intCast(number.len)));
        }
        for (ratcheted, 0..) |metric, index| {
            const value = group.counts[@backingInt(metric)];
            if (index % 6 == 0) try writer.writeAll("                ");
            const number = try std.fmt.bufPrint(&buffer, "{d}", .{value});
            try writer.print("{s},", .{number});
            if (index % 6 == 5 or index == ratcheted.len - 1) {
                try writer.writeByte('\n');
            } else {
                const padding = widths[index % 6] - number.len + 1;
                try writer.splatByteAll(' ', padding);
            }
        }
        try writer.writeAll("            },\n        },\n");
    }
    try writer.writeAll("    },\n}\n");
    try std.Io.Dir.cwd().writeFile(state.io, .{
        .sub_path = ratchet_path,
        .data = writer.buffered(),
    });
    assert(writer.end <= report_bytes_max);
    try state.output.print("tidy: tightened {s}\n", .{ratchet_path});
}
